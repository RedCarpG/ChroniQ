// Generates src/lib/brightStars.ts: the stars to magnitude 5 for the 此刻天空
// map, from d3-celestial's stars.6.json (BSD-3-Clause; XHIP, Anderson &
// Francis 2012). The source file is not kept in the repo; download it first:
//   https://raw.githubusercontent.com/ofrohn/d3-celestial/master/data/stars.6.json
// Run: npm run gen:stars -- path/to/stars.6.json
import { readFileSync, writeFileSync } from 'node:fs'

const MAG_LIMIT = 5

interface Feature {
  id: number
  properties: { mag: number; bv: string }
  geometry: { coordinates: [number, number] }
}

const path = process.argv[2]
if (!path) throw new Error('usage: npm run gen:stars -- path/to/stars.6.json')
const { features } = JSON.parse(readFileSync(path, 'utf8')) as { features: Feature[] }

const rows = features
  .filter((f) => f.properties.mag <= MAG_LIMIT)
  .sort((a, b) => a.properties.mag - b.properties.mag)
  .map((f) => {
    const [lon, dec] = f.geometry.coordinates
    const ra = lon < 0 ? lon + 360 : lon // d3-celestial keeps RA in −180…180
    const bv = Number(f.properties.bv)
    return [f.id, +ra.toFixed(2), +dec.toFixed(2), f.properties.mag, Number.isFinite(bv) ? +bv.toFixed(2) : 0.6]
  })

const out = `// Generated by scripts/gen-stars.ts from d3-celestial's stars.6.json
// (BSD-3-Clause; data from XHIP, Anderson & Francis 2012). Do not edit.
// Stars to magnitude ${MAG_LIMIT}, brightest first, as flat rows of
// [Hipparcos number, RA (°, J2000), Dec (°, J2000), magnitude, B−V colour index].
export const BRIGHT_STARS: readonly number[] = [
${rows.map((r) => '  ' + r.join(', ') + ',').join('\n')}
]
export const STAR_FIELDS = 5
`
writeFileSync(new URL('../src/lib/brightStars.ts', import.meta.url), out)
console.log(`${rows.length} stars written`)
