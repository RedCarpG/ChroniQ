// Generates src/lib/tradChars.ts: a per-character 简→繁 map covering every term
// collectTerms() finds, derived from OpenCC (cn → t). Run: npm run gen:trad
import { writeFileSync } from 'node:fs'
import { TRAD_TERMS } from '../src/lib/tradOverrides'
import { convertTrad, expectedTrad } from './opencc'
import { collectTerms } from './terms'

const map = new Map<string, { to: string; term: string }>()
const conflicts: string[] = []
const terms = collectTerms([1900, 2100])
for (const term of terms) {
  if (TRAD_TERMS[term]) continue // handled whole, not per character
  const src = [...term]
  const dst = [...expectedTrad(term)]
  if (src.length !== dst.length) throw new Error(`length changed: ${term} → ${dst.join('')}`)
  src.forEach((c, i) => {
    // Record unchanged characters too, so 天干 (干 stays) vs 幹 shows up as a conflict.
    const prev = map.get(c)
    if (prev && prev.to !== dst[i]) conflicts.push(`${c}: ${prev.to} (${prev.term}) / ${dst[i]} (${term})`)
    else if (!prev) map.set(c, { to: dst[i], term })
  })
}
if (conflicts.length) {
  console.error('Ambiguous characters; add them to TRAD_OVERRIDES:\n' + conflicts.join('\n'))
  process.exit(1)
}

const entries = [...map]
  .filter(([s, { to }]) => s !== to)
  .map(([s, { to }]) => [s, to] as const)
  .sort(([a], [b]) => a.localeCompare(b, 'zh'))
writeFileSync(
  'src/lib/tradChars.ts',
  `// Generated by scripts/gen-trad.ts from OpenCC (cn → t) over ${terms.length} terms. Do not edit by hand.\n` +
    `export const TRAD_CHARS: Record<string, string> = {\n` +
    entries.map(([s, t]) => `  '${s}': '${t}',`).join('\n') +
    `\n}\n`,
)
// 繁體中文 converts whole texts with OpenCC (src/lib/hant.ts), terms already in 繁體 among them: where
// OpenCC would turn a term's 繁體 form into something else, it is turned back
const fixes = new Map<string, string>()
for (const term of terms) {
  const right = expectedTrad(term)
  // The term already in 繁體 (term()), and in 简体 inside a sentence (t()): single characters are
  // left alone, as only the words around them can say which form they take
  for (const from of [right, term]) {
    const wrong = convertTrad(from)
    if (wrong !== right && [...term].length > 1) fixes.set(wrong, right)
  }
}
const fixList = [...fixes].sort(([a], [b]) => b.length - a.length || a.localeCompare(b, 'zh'))
writeFileSync(
  'src/lib/hantFixes.ts',
  `// Generated by scripts/gen-trad.ts: terms whose 繁體 form OpenCC (cn → t) would change again. Do not edit by hand.\n` +
    `export const HANT_FIXES: [string, string][] = [\n` +
    fixList.map(([w, r]) => `  ['${w}', '${r}'],`).join('\n') +
    (fixList.length ? '\n' : '') +
    `]\n`,
)
console.log(`${terms.length} terms, ${entries.length} characters, ${fixList.length} fixes for 繁體中文`)
