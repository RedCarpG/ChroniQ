// Generates the constellation figures for the 此刻天空 map from d3-celestial's
// data (https://github.com/ofrohn/d3-celestial/tree/master/data), which is not
// kept in the repo; download these four files into one folder first:
//   constellations.lines.json, constellations.json            (Western, BSD-3-Clause)
//   constellations.lines.cn.json, constellations.cn.json      (Chinese 星官, from
//     Stellarium's "chinese" sky culture, CC BY-SA 4.0)
// Run: npm run gen:constellations -- path/to/folder
// Writes src/lib/constellations.ts (Western) and src/lib/xingguan.ts (Chinese).
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import * as OpenCC from 'opencc-js'
import { expectedTrad } from './opencc'

interface LineFeature {
  id: string
  properties: { rank: string | number }
  geometry: { coordinates: [number, number][][] }
}
interface NameFeature {
  id: string
  properties: { name: string; zh?: string; en?: string; rank: string | number }
  geometry: { coordinates: [number, number] }
}

const dir = process.argv[2]
if (!dir) throw new Error('usage: npm run gen:constellations -- path/to/folder')
const read = <T>(f: string) => (JSON.parse(readFileSync(join(dir, f), 'utf8')) as { features: T[] }).features
// d3-celestial keeps RA in −180…180; RA and Dec in degrees, J2000
const ra = (lon: number) => +(lon < 0 ? lon + 360 : lon).toFixed(2)
const dec = (lat: number) => +lat.toFixed(2)
const toSimplified = OpenCC.Converter({ from: 'tw', to: 'cn' })

function build(lineFile: string, nameFile: string, name: (f: NameFeature) => string) {
  const names = new Map(read<NameFeature>(nameFile).map((f) => [String(f.id), f]))
  return read<LineFeature>(lineFile).map((f) => {
    const n = names.get(String(f.id))!
    const [lon, lat] = n.geometry.coordinates
    return {
      id: String(f.id),
      name: name(n),
      trad: expectedTrad(name(n)),
      en: n.properties.en ?? n.properties.name,
      rank: Number(f.properties.rank),
      label: [ra(lon), dec(lat)],
      lines: f.geometry.coordinates.map((line) => line.flatMap(([lon, lat]) => [ra(lon), dec(lat)])),
    }
  })
}

const rows = (list: ReturnType<typeof build>) =>
  list
    .map(
      (c) =>
        `  { id: ${JSON.stringify(c.id)}, name: ${JSON.stringify(c.name)}, trad: ${JSON.stringify(c.trad)}, en: ${JSON.stringify(c.en)}, rank: ${c.rank}, ` +
        `label: [${c.label.join(', ')}], lines: [${c.lines.map((l) => `[${l.join(',')}]`).join(', ')}] },`,
    )
    .join('\n')

const western = build('constellations.lines.json', 'constellations.json', (f) => toSimplified(f.properties.zh!))
writeFileSync(
  new URL('../src/lib/constellations.ts', import.meta.url),
  `// Generated by scripts/gen-constellations.ts from d3-celestial's constellations.lines.json
// and constellations.json (BSD-3-Clause). Do not edit.
// The 88 Western constellations: Chinese and English names, a label point, and
// the stick figures as polylines of [RA, Dec, RA, Dec, …] (degrees, J2000).
// rank 1–3: how prominent (1 = the best known), used to choose which to label.
import type { Constellation } from './sky'

export const WESTERN: Constellation[] = [
${rows(western)}
]
`,
)

const chinese = build('constellations.lines.cn.json', 'constellations.cn.json', (f) => f.properties.name)
writeFileSync(
  new URL('../src/lib/xingguan.ts', import.meta.url),
  `// Generated by scripts/gen-constellations.ts from d3-celestial's constellations.lines.cn.json
// and constellations.cn.json, which come from Stellarium's "chinese" sky culture
// (https://github.com/Stellarium/stellarium/tree/master/skycultures/chinese).
// Licence: CC BY-SA 4.0 (https://creativecommons.org/licenses/by-sa/4.0/); this
// file, derived from it, is shared under the same licence. Do not edit.
// The traditional Chinese 星官 (三垣二十八宿 and the rest): name, an English
// gloss, a label point, and the figures as polylines of [RA, Dec, …] (degrees,
// J2000). rank 1 = the 28 宿, 2 = the next best known, 3 = the rest.
import type { Constellation } from './sky'

export const XINGGUAN: Constellation[] = [
${rows(chinese)}
]
`,
)
console.log(`${western.length} Western constellations, ${chinese.length} 星官 written`)
